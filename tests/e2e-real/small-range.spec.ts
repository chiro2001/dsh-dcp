function user(text: string) {
  return createUserMessage({ content: [{ type: 'text', text }], source: { kind: 'user' } })
}

function setupTurn(text: string): string {
  return `${text}\n\nFor this setup turn only, do not call tools or compress. Reply exactly READY.`
}

function textOf(message: { content: readonly { type: string; text?: string }[] }): string {
  return message.content
    .filter((block) => block.type === 'text')
    .map((block) => (block.type === 'text' ? block.text : ''))
    .join('\n')
}

function makeOfflineHistory(): SessionType {
  const session = Session.create(SessionId('small-range-offline-calibration'))
  for (let turn = 1; turn <= 3; turn++) {
    session.append('turn/start', { turn })
    session.append('step/start', { turn, step: 1 })
    session.append(
      'user/message',
      buildStepMarkerMessage(`m${String(turn).padStart(4, '0')}`, turn, 1),
      { surfaceOp: 'append' },
    )
    session.append(
      'user/message',
      user(
        setupTurn(
          turn === 1
            ? SMALL_RANGE_NOTES
            : `Release phase ${turn}: staging healthy; operator review pending.`,
        ),
      ),
      { surfaceOp: 'append' },
    )
    session.append(
      'assistant/message',
      {
        turn,
        step: 1,
        stream: [],
        message: createAssistantMessage({
          content: [{ type: 'text', text: 'READY' }],
          source: { provider: 'small-range-fixture', model: 'small-range-fixture' },
        }),
      },
      { surfaceOp: 'append' },
    )
    session.append('step/end', { turn, step: 1 })
    session.append('turn/end', { turn, reason: { kind: 'completed' } })
  }
  return session
}

function markerSequence(session: SessionType, ref: string): SessionSeq | undefined {
  for (const seq of session.surface.nodes) {
    const event = session.eventAt(seq)
    if (event?.type !== 'user/message' || event.data.source.kind !== 'dsh-dcp') continue
    for (const block of event.data.content) {
      if (block.type !== 'text') continue
      for (const line of block.text.split('\n')) {
        if (parseBoundaryMarker(line)?.ref === ref) return seq
      }
    }
  }
  return undefined
}

function rangeTokens(session: SessionType): number {
  const startSeq = markerSequence(session, 'm0001')
  const endSeq = markerSequence(session, 'm0002')
  if (startSeq === undefined || endSeq === undefined)
    throw new Error('small range boundaries missing')
  const surface = session.surface.nodes
  const start = surface.indexOf(startSeq)
  const end = surface.indexOf(endSeq)
  if (start < 0 || end <= start) throw new Error('small range boundaries are not ordered')
  const prices = new Map(
    fixture.ctx.tokenMeter
      .measure(session)
      .nodes.map((node) => [node.seq, node.heuristicTokens]),
  )
  return surface.slice(start, end).reduce((sum, seq) => sum + (prices.get(seq) ?? 0), 0)
}

function compress(session: SessionType, minNetSavingsTokens: number) {
  return executeCompressRange(
    session,
    fixture.ctx.tokenMeter,
    resolveConfig({ compress: { minNetSavingsTokens } }),
    {
      topic: 'helios-r17 release',
      content: [{ startRef: 'm0001', endRef: 'm0002', summary: SUMMARY }],
    },
    {
      compactionId: CompactionId(`small-range-${minNetSavingsTokens}`),
      compressCallId: `small-range-call-${minNetSavingsTokens}`,
      authorMessageId: `small-range-author-${minNetSavingsTokens}`,
    },
  )
}

function checkpointTexts(session: SessionType): string[] {
  return session.snapshotEvents().flatMap((event) => {
    if (event.type !== 'user/message') return []
    const decoded = decodeDcpMeta(event.data.source)
    return decoded.ok && decoded.meta.kind === 'summary' ? [textOf(event.data)] : []
  })
}

describe('scripted small-range scaffold', () => {
  it('calibrates a short range that clears a low savings threshold', () => {
    const session = makeOfflineHistory()
    const tokens = rangeTokens(session)
    console.log(
      `SMALL_RANGE_CALIBRATION ${JSON.stringify({ rangeTokens: tokens, minNetSavingsTokens: MIN_SAVINGS, strictMinNetSavingsTokens: STRICT_MIN_SAVINGS })}`,
    )
    expect(tokens).toBeGreaterThanOrEqual(300)
    expect(tokens).toBeLessThanOrEqual(420)

    const result = compress(session, MIN_SAVINGS)
    expect(result.status).toBe('success')
    expect(result.failed).toHaveLength(0)
    expect(result.blocks).toHaveLength(1)
    expect(checkpointTexts(session).join('\n')).toContain(SUMMARY)

    const visible = session.deriveMessages().map(textOf).join('\n')
    expect(visible).toContain(RECOVERY_PHRASE)
    expect(visible).toContain(ARTIFACT)
    expect(visible).toContain(OPEN_TASK)
    expect(visible).not.toContain('Snapshot 1:')
  })

  it('rejects the same range at a strict threshold and leaves the source visible', () => {
    const session = makeOfflineHistory()
    const tokens = rangeTokens(session)
    expect(tokens).toBeGreaterThanOrEqual(300)
    expect(tokens).toBeLessThanOrEqual(420)

    let error: Error | undefined
    try {
      compress(session, STRICT_MIN_SAVINGS)
    } catch (caught) {
      if (caught instanceof Error) error = caught
      else throw caught
    }
    expect(error).toBeDefined()
    const code = classifyCompressError(error)
    expect(code).toBe('INSUFFICIENT_SAVINGS')
    expect(correctionForCompressFailure(code, error)).toContain('skip this range')
    expect(checkpointTexts(session)).toHaveLength(0)

    const visible = session.deriveMessages().map(textOf).join('\n')
    expect(visible).toContain(RECOVERY_PHRASE)
    expect(visible).toContain(ARTIFACT)
    expect(visible).toContain(OPEN_TASK)
    expect(visible).toContain('Snapshot 1:')
  })
})

describe.skipIf(!realConfig)('real provider small-range quality', () => {
  for (const minNetSavingsTokens of [MIN_SAVINGS, STRICT_MIN_SAVINGS]) {
    const succeeds = minNetSavingsTokens === MIN_SAVINGS
    it(
      succeeds
        ? 'real small range: writes compact factual prose and recalls only from its checkpoint'
        : 'real small range: skips an impossible savings target and retains the original facts',
      { timeout: 90_000 },
      async () => {
        if (!realConfig) throw new Error('real model not configured')
        const isolated = await mkdtemp(join(tmpdir(), 'dsh-dcp-real-small-'))
        const envNames = ['DSH_HOME', 'XDG_DATA_HOME', 'XDG_CONFIG_HOME'] as const
        const saved = envNames.map((name) => process.env[name])
        for (const name of envNames) process.env[name] = join(isolated, name)
        await Promise.all(
          envNames.map((name) => mkdir(process.env[name]!, { recursive: true })),
        )
        const ctx = new Context()
        const adapter = new OpenCodeGoAdapter(realConfig)
        let budgetExceeded = false
        try {
          await ctx.plugin(InvariantRegistry)
          await mountAgentLoopTestDependencies(ctx, {
            systemPrompt: {
              personaPrefix:
                'You are a DeepSeek Harness agent. Follow DCP rules and preserve exact facts.',
            },
          })
          await ctx.plugin(sessionInvariant as unknown as Plugin)
          await ctx.plugin(agentLoopInvariant as unknown as Plugin)
          await ctx.plugin(compactionInvariant as unknown as Plugin)
          await ctx.plugin(TokenMeter)
          await ctx.plugin(CommandRuntime)
          await ctx.plugin(AgentLoop, { agents: [] })
          ctx.llm.registerAdapter([realConfig.provider], adapter)
          const requestsByTurn = new Map<number, number>()
          ctx.on('agent/pre-step', async ({ turn }, next) => {
            const count = (requestsByTurn.get(turn) ?? 0) + 1
            requestsByTurn.set(turn, count)
            if (count > 4) {
              budgetExceeded = true
              return { kind: 'reject' }
            }
            return next()
          })
          await ctx.plugin(
            dcpPlugin as unknown as Plugin,
            resolveConfig({ compress: { minNetSavingsTokens } }),
          )
          const agent = await ctx.agentLoop.create(
            SessionId(`real-small-${minNetSavingsTokens}`),
            {
              provider: realConfig.provider,
              model: realConfig.model,
              maxTokens: 1536,
            },
          )
          function diagnostics(): string {
            return JSON.stringify({
              minNetSavingsTokens,
              requests: adapter.requestDiagnostics,
              responses: adapter.responseDiagnostics,
              visible: agent.session.deriveMessages(),
              toolEvents: agent.session
                .snapshotEvents()
                .filter((event) => event.type === 'tool/call' || event.type === 'tool/result'),
            })
          }
          function check(condition: unknown, message: string): asserts condition {
            if (!condition) throw new Error(`${message}\nSafe diagnostics: ${diagnostics()}`)
          }
          async function followup(text: string): Promise<void> {
            const offset = adapter.responseDiagnostics.length
            const idle = new Promise<void>((resolve) => {
              const dispose = ctx.on('agent/status', ({ agent: current, status }) => {
                if (current.id === agent.id && status === 'idle') {
                  dispose()
                  resolve()
                }
              })
            })
            agent.followup(user(text))
            await idle
            const responses = adapter.responseDiagnostics.slice(offset)
            check(!budgetExceeded, 'small-range per-turn request budget exceeded')
            check(
              responses.length > 0 &&
                responses.every((response) => response.httpStatus === 200),
              'small-range provider transport failed',
            )
            check(
              responses.every((response) => response.finishReason !== 'length'),
              'small-range output was truncated at maxTokens',
            )
            const turnEnd = agent.session
              .snapshotEvents()
              .findLast((event) => event.type === 'turn/end')
            check(
              turnEnd?.type === 'turn/end' && turnEnd.data.reason.kind === 'completed',
              'small-range turn did not complete successfully',
            )
          }
          function calls() {
            return agent.session
              .snapshotEvents()
              .filter(
                (event): event is Extract<SessionEvent, { type: 'tool/call' }> =>
                  event.type === 'tool/call' && event.data.name === 'compress',
              )
          }
          function answer(turn: number): string {
            return agent.session
              .snapshotEvents()
              .flatMap((event) =>
                event.type === 'assistant/message' && event.data.turn === turn
                  ? [textOf(event.data.message)]
                  : [],
              )
              .join('\n')
          }
          const source = setupTurn(SMALL_RANGE_NOTES)
          await followup(source)
          await followup(setupTurn('Staging phase: healthy; operator review pending.'))
          await followup(setupTurn('Review phase: rollout deferred until operator signoff.'))
          check(calls().length === 0, 'model compressed before the explicit request')
          const originalTokens = rangeTokens(agent.session)
          check(
            originalTokens >= 300 && originalTokens <= 420,
            'small-range calibration drifted',
          )
          const prompt =
            'Make one initial native `compress` call now for m0001..m0002 only. Emit no accompanying prose with tool calls. Write a compact factual summary yourself from the release notes, preserving literal identifiers, decisions, constraints and open work; fold repeated status snapshots. Do not expand the range. Follow the returned correction. After the result, reply only READY without repeating facts.'
          for (const value of [RECOVERY_PHRASE, ARTIFACT, OPEN_TASK])
            expect(prompt).not.toContain(value)
          await followup(prompt)
          const submitted = calls()
          check(submitted.length === 1, 'model repeated or omitted the small-range call')
          const call = submitted[0]!
          const args = JSON.parse(call.data.arguments) as {
            content: Array<{ startRef: string; endRef: string; summary: string }>
          }
          check(
            args.content.length === 1 &&
              args.content[0]?.startRef === 'm0001' &&
              args.content[0]?.endRef === 'm0002',
            'model changed the requested small range',
          )
          const generated = args.content[0]!.summary
          function preservesDecisionsAndConstraints(text: string): boolean {
            return (
              /idempotency/i.test(text) &&
              /stable|unchanged/i.test(text) &&
              /migrat/i.test(text) &&
              /cursor/i.test(text) &&
              /lag/i.test(text) &&
              /\bzero\b|\b0\b/i.test(text)
            )
          }
          check(
            preservesDecisionsAndConstraints(generated),
            'small summary lost the migration decision or rollback constraint',
          )
          check(generated.length < SMALL_RANGE_NOTES.length, 'small summary was not compact')
          check(
            !/\b(?:Goal|Constraints|Decisions|Artifacts|Failures|Verification|Open work):\s*(?:none|n\/a)\b/i.test(
              generated,
            ),
            'small summary filled empty template fields',
          )
          for (const value of [
            RECOVERY_PHRASE,
            ARTIFACT,
            OPEN_TASK,
            '8f15c299a3e1d429',
            'shard-07',
            'pool-cobalt',
          ]) {
            check(generated.includes(value), `small summary omitted ${value}`)
          }
          const result = agent.session
            .snapshotEvents()
            .find(
              (event) =>
                event.type === 'tool/result' &&
                event.data.message.source.callId === call.data.callId,
            )
          check(result?.type === 'tool/result', 'small-range native result missing')
          const outcome = textOf(result.data.message)
          const settled = agent.session
            .snapshotEvents()
            .findLast(
              (event) =>
                event.type === 'assistant/message' &&
                event.data.turn === 4 &&
                event.seq > result.seq,
            )
          const ready =
            settled?.type === 'assistant/message' ? textOf(settled.data.message) : ''
          check(
            ready.trim() === 'READY',
            'small-range native result was not acknowledged with READY',
          )
          const visible = agent.session.deriveMessages()
          const activeCheckpoints = visible.filter((message) => {
            const decoded = decodeDcpMeta(message.source)
            return decoded.ok && decoded.meta.kind === 'summary'
          })
          if (succeeds) {
            check(
              outcome.includes('status=success'),
              'low-threshold small range did not commit',
            )
            check(activeCheckpoints.length === 1, 'small checkpoint is not active')
            check(
              !visible.some(
                (message) => message.source.kind === 'user' && textOf(message) === source,
              ),
              'small original source is still visible',
            )
            const others = JSON.stringify(
              visible.filter((message) => !activeCheckpoints.includes(message)),
            )
            for (const value of [RECOVERY_PHRASE, ARTIFACT, OPEN_TASK]) {
              check(
                textOf(activeCheckpoints[0]!).includes(value),
                `small checkpoint omitted ${value}`,
              )
              check(!others.includes(value), `small recall has another carrier for ${value}`)
            }
            check(
              visible.some((message) => textOf(message).startsWith('<dcp-cleanup')),
              'small native call/result was not archived',
            )
          } else {
            check(
              outcome.includes('status=rejected') && outcome.includes('[INSUFFICIENT_SAVINGS]'),
              'strict small range was not rejected for savings',
            )
            check(outcome.includes('skip this range'), 'strict result omitted skip correction')
            check(
              checkpointTexts(agent.session).length === 0,
              'strict range wrote a checkpoint',
            )
            check(
              visible.some(
                (message) => message.source.kind === 'user' && textOf(message) === source,
              ),
              'strict rejection removed the original source',
            )
          }
          const recallPrompt =
            'What exact recovery phrase, artifact path and open task were in the release notes? What decision governed idempotency keys during migration, and what condition protected the queue cursor?'
          for (const value of [RECOVERY_PHRASE, ARTIFACT, OPEN_TASK])
            expect(recallPrompt).not.toContain(value)
          await followup(recallPrompt)
          for (const value of [RECOVERY_PHRASE, ARTIFACT, OPEN_TASK])
            check(answer(5).includes(value), `small recall omitted ${value}`)
          check(calls().length === 1, 'model retried the small range during recall')
          check(
            preservesDecisionsAndConstraints(answer(5)),
            'small recall lost the migration decision or rollback constraint',
          )
          const sum = (key: 'inputTokens' | 'cacheReadTokens' | 'outputTokens') =>
            adapter.responseDiagnostics.reduce(
              (total, response) => total + (response.usage?.[key] ?? 0),
              0,
            )
          const uncachedInputTokens = sum('inputTokens')
          const cacheReadTokens = sum('cacheReadTokens')
          console.log(
            `REAL_MODEL_METRICS ${JSON.stringify({
              scenario: succeeds ? 'small-summary-recall' : 'small-savings-rejection',
              model: realConfig.model,
              provider: realConfig.provider,
              minNetSavingsTokens,
              originalRangeTokens: originalTokens,
              submittedSummaryChars: generated.length,
              submittedSummary: generated,
              estimatedSummaryTokens: ctx.tokenMeter.estimateMessage(user(generated)),
              outcome: succeeds ? 'success' : 'INSUFFICIENT_SAVINGS',
              requestCount: adapter.requestDiagnostics.length,
              uncachedInputTokens,
              cacheReadTokens,
              promptTokens: uncachedInputTokens + cacheReadTokens,
              outputTokens: sum('outputTokens'),
              nativeCallCount: calls().length,
              decisionsAndConstraints: true,
              recall: true,
            })}`,
          )
        } finally {
          await ctx.fiber.dispose()
          const files = await readdir(isolated, { recursive: true, withFileTypes: true })
          const leaked = await Promise.all(
            files
              .filter((entry) => entry.isFile())
              .map(async (entry) =>
                (await readFile(join(entry.parentPath, entry.name))).includes(
                  Buffer.from(realConfig.apiKey),
                ),
              ),
          )
          for (let index = 0; index < envNames.length; index++) {
            const name = envNames[index]!
            if (saved[index] === undefined) delete process.env[name]
            else process.env[name] = saved[index]
          }
          await rm(isolated, { recursive: true, force: true })
          expect(leaked.some(Boolean)).toBe(false)
        }
      },
    )
  }
})
